#include "screen.h"
#include <stdio.h>

/***********************************************************
*@函数	:Screen_Send
*@功能	:发送一条串口屏指令(自动补帧尾FF FF FF)
*@参数	:s--指令字符串
*@日期	:2026-10-22
***********************************************************/
void Screen_Send(char *s)
{
    printf("%s\xff\xff\xff", s);
}

/***********************************************************
*@函数	:Screen_Set_Text
*@功能	:给文本控件赋值,如 t0.txt="hello"
*@参数	:obj--控件名  txt--文本内容
*@日期	:2026-10-22
***********************************************************/
void Screen_Set_Text(char *obj, char *txt)
{
    printf("%s.txt=\"%s\"\xff\xff\xff", obj, txt);
}

/***********************************************************
*@函数	:Screen_Set_Color
*@功能	:设置控件字体颜色并刷新
*@参数	:obj--控件名  color--RGB565颜色
*@日期	:2026-10-22
***********************************************************/
void Screen_Set_Color(char *obj, u16 color)
{
    printf("%s.pco=%d\xff\xff\xff", obj, color);
    printf("ref %s\xff\xff\xff", obj);
}

/***********************************************************
*@函数	:Screen_Page
*@功能	:切换串口屏页面
*@参数	:page--页面编号(0主页 1监测页 2设置页)
*@日期	:2026-10-22
***********************************************************/
void Screen_Page(u8 page)
{
    printf("page %d\xff\xff\xff", page);
}
