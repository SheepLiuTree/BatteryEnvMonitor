static u8 OW_Read_Byte(void)
{
    u8 i, dat = 0;

    for (i = 0; i < 8; i++)
    {
        dat >>= 1;
        if (OW_Read_Slot()) dat |= 0x80;
    }

    return dat;
}

/***********************************************************
*@????	:DS18B20_CRC8
*@????	:????DS18B20??CRC8§µ??(?????X^8+X^5+X^4+1)
*@????	:§µ???(ROM????????????§µ??????????0)
*@????	:2026-10-22
***********************************************************/
u8 DS18B20_CRC8(u8 *buf, u8 len)
{
    u8 crc = 0;
    u8 i, dat, mix;

    while (len--)
    {
        dat = *buf++;
        for (i = 8; i; i--)
        {
            mix = (crc ^ dat) & 0x01;
            crc >>= 1;
            if (mix) crc ^= 0x8C;
            dat >>= 1;
        }
    }

    return crc;
}

