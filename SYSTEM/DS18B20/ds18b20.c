/***********************************************************
*@????	:DS18B20_Search
*@????	:???????????????64¦ËROM??
*@????	:rom--??????????????(8???)
*@????	:1=?????????ROM,0=???????????
*@????	:2026-10-22
***********************************************************/
u8 DS18B20_Search(u8 *rom)
{
    u8 id_bit_number, last_zero, rom_byte_number, rom_bit_number;
    u8 id_bit, cmp_id_bit;
    u8 search_direction, search_result;

    if (LastDeviceFlag)                                     //??????????????????
    {
        DS18B20_Search_Reset();
        return 0;
    }

    if (!OW_Reset())                                        //????????????
    {
        DS18B20_Search_Reset();
        return 0;
    }

    OW_Write_Byte(0xF0);                                    //????ROM????
    id_bit_number = 1;
    last_zero = 0;
    rom_byte_number = 0;
    rom_bit_number = 0;

    do
    {
        id_bit = OW_Read_Slot();                            //?????¦Ë
        cmp_id_bit = OW_Read_Slot();                        //??????¦Ë

        if (id_bit && cmp_id_bit) break;                    //?????????,???

        if (id_bit == cmp_id_bit)                           //??¦Ë???????(0??1????????)
        {
            if (id_bit_number == LastDiscrepancy) search_direction = 1;
            else if (id_bit_number > LastDiscrepancy) search_direction = 0;
            else search_direction = (rom_id[rom_byte_number] >> rom_bit_number) & 0x01;

            if (search_direction == 0)
            {
                last_zero = id_bit_number;                  //???????¦Ë
            }
        }
        else
        {
            search_direction = id_bit;                      //??¦Ë???????????
        }

        if (search_direction)                               //?????¦Ë??ROM????
        {
            rom_id[rom_byte_number] |= 1 << rom_bit_number;
        }
        else
        {
            rom_id[rom_byte_number] &= ~(1 << rom_bit_number);
        }

        OW_Write_Slot(search_direction);                    //???????????

        id_bit_number++;
        rom_bit_number++;
        if (rom_bit_number == 8)
        {
            rom_bit_number = 0;
            rom_byte_number++;
        }
    } while (rom_byte_number < 8);                          //64¦Ë???????

    if (id_bit_number < 65) search_result = 0;              //??????
    else if (DS18B20_CRC8(rom_id, 8) != 0) search_result = 0;   //CRC§µ?????
    else search_result = 1;                                 //???????

    if (search_result)
    {
        LastDiscrepancy = last_zero;
        if (LastDiscrepancy == 0) LastDeviceFlag = 1;       //?????¦Â???¦Ë?0,????????
        for (id_bit = 0; id_bit < 8; id_bit++) rom[id_bit] = rom_id[id_bit];
    }
    else
    {
        DS18B20_Search_Reset();
    }

    return search_result;
}

