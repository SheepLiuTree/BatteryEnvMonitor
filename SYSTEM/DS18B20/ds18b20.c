u8 DS18B20_Search_All(u8 rom_tab[][8], u8 max_num)
{
    u8 cnt = 0;
    u8 rom[8];
    u8 i;

    DS18B20_Search_Reset();
    while (DS18B20_Search(rom))
    {
        if (cnt >= max_num) break;
        for (i = 0; i < 8; i++) rom_tab[cnt][i] = rom[i];
        cnt++;
    }

    return cnt;
}

