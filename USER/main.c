        if (--mon_wait == 0)
        {
            mon_idx = 0;
            mon_state = 2;
        }
        break;

    case 2:                                             //??????(?????)
        temp_tab[mon_idx] = DS18B20_Read_Temp_By_Rom(g_store.rom_tab[mon_idx]);
